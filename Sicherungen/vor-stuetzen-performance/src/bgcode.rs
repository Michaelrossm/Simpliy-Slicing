//! Binaerer G-Code (libbgcode): Vorschaubilder als Bloecke einfuegen.
//! Aufbau: Dateikopf "GCDE", Version u32, Pruefsummentyp u16; danach Bloecke aus
//! Typ u16, Kompression u16, unkomprimierte Groesse u32, [komprimierte Groesse u32], Parameter, Daten, [CRC32].
//! Vorschaubilder (Typ 5) stehen nach den Drucker-Metadaten (Typ 3).

const MAGIC: &[u8; 4] = b"GCDE";
const FILE_METADATA: u16 = 0;
const GCODE: u16 = 1;
const SLICER_METADATA: u16 = 2;
const PRINTER_METADATA: u16 = 3;
const PRINT_METADATA: u16 = 4;
const THUMBNAIL: u16 = 5;
const PNG: u16 = 0;
const GCODE_CHUNK: usize = 65535;

/// Schluessel, die PrusaSlicer in die Drucker-Metadaten schreibt (Firmware und Weboberflaechen lesen sie).
const PRINTER_KEYS: [&str; 16] = [
    "printer_model", "filament_type", "nozzle_diameter", "bed_temperature", "brim_width", "fill_density", "layer_height",
    "temperature", "ironing", "support_material", "max_layer_z", "extruder_colour", "filament used [mm]", "filament used [g]",
    "estimated printing time (normal mode)", "filament cost",
];

fn block(kind: u16, params: &[u8], data: &[u8]) -> Vec<u8> {
    let mut b = Vec::with_capacity(data.len() + 16);
    b.extend_from_slice(&kind.to_le_bytes());
    b.extend_from_slice(&0u16.to_le_bytes());
    b.extend_from_slice(&(data.len() as u32).to_le_bytes());
    b.extend_from_slice(params);
    b.extend_from_slice(data);
    let sum = crc32fast::hash(&b);
    b.extend_from_slice(&sum.to_le_bytes());
    b
}

/// Text-G-Code der Engine in echten binaeren G-Code wandeln (unkomprimiert, CRC32).
/// Die Engine schreibt ueber die Kommandozeile auch mit `binary_gcode` nur Text.
/// Vorhandene Vorschaubilder im Text werden zu Bildbloecken.
pub fn from_ascii(text: &str) -> Vec<u8> {
    let ini = 0u16.to_le_bytes(); // Kodierung: INI bzw. G-Code ohne Kodierung
    let mut config = String::new();
    let mut summary = String::new();
    let mut gcode = String::with_capacity(text.len());
    let mut thumbnails: Vec<(u16, u16, String)> = Vec::new();
    let mut in_config = false;
    let mut thumb: Option<(u16, u16, String)> = None;
    let mut producer = String::from("Simpliy Slicing");
    for line in text.split_inclusive('\n') {
        let bare = line.trim_end();
        if let Some(head) = bare.strip_prefix("; thumbnail begin ") {
            let size = head.split_whitespace().next().unwrap_or("");
            let (w, h) = size.split_once('x').unwrap_or(("0", "0"));
            thumb = Some((w.parse().unwrap_or(0), h.parse().unwrap_or(0), String::new()));
            continue;
        }
        if let Some((w, h, data)) = thumb.as_mut() {
            if bare == "; thumbnail end" {
                thumbnails.push((*w, *h, std::mem::take(data)));
                thumb = None;
            } else {
                data.push_str(bare.trim_start_matches(';').trim());
            }
            continue;
        }
        if bare == "; prusaslicer_config = begin" {
            in_config = true;
            continue;
        }
        if bare == "; prusaslicer_config = end" {
            in_config = false;
            continue;
        }
        if let Some(rest) = bare.strip_prefix("; generated by ") {
            producer = rest.split(" on ").next().unwrap_or(rest).to_owned();
        }
        let pair = bare.strip_prefix("; ").and_then(|t| t.split_once(" = "));
        if in_config {
            if let Some((k, v)) = pair {
                config += &format!("{k}={v}\n");
            }
            continue;
        }
        if let Some((k, v)) = pair {
            if k.starts_with("filament used") || k.starts_with("total ") || k.starts_with("estimated ") || k == "filament cost" {
                summary += &format!("{k}={v}\n");
            }
        }
        gcode.push_str(line);
    }
    let lookup = |key: &str| -> Option<String> {
        [&summary, &config].iter().flat_map(|s| s.lines()).find_map(|l| l.split_once('=').filter(|(k, _)| *k == key).map(|(_, v)| v.to_owned()))
    };
    let mut printer = String::new();
    for key in PRINTER_KEYS {
        if let Some(value) = lookup(key) {
            printer += &format!("{key}={value}\n");
        }
    }
    let mut out = MAGIC.to_vec();
    out.extend_from_slice(&1u32.to_le_bytes());
    out.extend_from_slice(&1u16.to_le_bytes()); // CRC32
    out.extend(block(FILE_METADATA, &ini, format!("Producer={producer}\n").as_bytes()));
    out.extend(block(PRINTER_METADATA, &ini, printer.as_bytes()));
    use base64::Engine;
    for (w, h, data) in thumbnails {
        if let Ok(png) = base64::engine::general_purpose::STANDARD.decode(data) {
            let mut params = PNG.to_le_bytes().to_vec();
            params.extend_from_slice(&w.to_le_bytes());
            params.extend_from_slice(&h.to_le_bytes());
            out.extend(block(THUMBNAIL, &params, &png));
        }
    }
    out.extend(block(PRINT_METADATA, &ini, summary.as_bytes()));
    out.extend(block(SLICER_METADATA, &ini, config.as_bytes()));
    // G-Code in Bloecken, nur an Zeilenenden getrennt.
    let bytes = gcode.as_bytes();
    let mut start = 0;
    while start < bytes.len() {
        let mut end = (start + GCODE_CHUNK).min(bytes.len());
        if end < bytes.len() {
            end = bytes[start..end].iter().rposition(|&b| b == b'\n').map_or(end, |i| start + i + 1);
        }
        out.extend(block(GCODE, &ini, &bytes[start..end]));
        start = end;
    }
    out
}

pub struct Block {
    pub kind: u16,
    pub end: usize,
}

fn u16_at(data: &[u8], at: usize) -> Result<u16, String> {
    data.get(at..at + 2).map(|b| u16::from_le_bytes([b[0], b[1]])).ok_or_else(|| "bgcode zu kurz".into())
}

fn u32_at(data: &[u8], at: usize) -> Result<u32, String> {
    data.get(at..at + 4).map(|b| u32::from_le_bytes([b[0], b[1], b[2], b[3]])).ok_or_else(|| "bgcode zu kurz".into())
}

/// Bloecke lesen und jede Pruefsumme kontrollieren.
pub fn blocks(data: &[u8]) -> Result<(bool, Vec<Block>), String> {
    if data.get(..4) != Some(MAGIC) {
        return Err("Kein binärer G-Code".into());
    }
    let crc = u16_at(data, 8)? == 1;
    let mut at = 10;
    let mut list = Vec::new();
    while at < data.len() {
        let start = at;
        let kind = u16_at(data, at)?;
        let compression = u16_at(data, at + 2)?;
        let size = u32_at(data, at + 4)? as usize;
        let mut header = 8;
        let payload = if compression == 0 {
            size
        } else {
            header = 12;
            u32_at(data, at + 8)? as usize
        };
        let params = if kind == THUMBNAIL { 6 } else { 2 };
        let body = start + header + params + payload;
        let end = body + if crc { 4 } else { 0 };
        if end > data.len() {
            return Err("bgcode-Block unvollständig".into());
        }
        if crc && crc32fast::hash(&data[start..body]) != u32_at(data, body)? {
            return Err(format!("bgcode-Prüfsumme falsch (Block bei {start})"));
        }
        list.push(Block { kind, end });
        at = end;
    }
    Ok((crc, list))
}

/// G-Code-Text aus einer bgcode-Datei zurücklesen (unkomprimierte Blöcke, wie `from_ascii` sie schreibt). Prüft dabei alle Blöcke.
#[allow(dead_code)]
pub fn gcode_text(data: &[u8]) -> Result<String, String> {
    let (crc, list) = blocks(data)?;
    let mut out = Vec::new();
    let mut start = 10;
    for block in &list {
        let kind = block.kind;
        let compression = u16_at(data, start + 2)?;
        let size = u32_at(data, start + 4)? as usize;
        if kind == GCODE {
            if compression != 0 {
                return Err("Komprimierte G-Code-Blöcke werden hier nicht gelesen.".into());
            }
            out.extend_from_slice(&data[start + 8 + 2..start + 8 + 2 + size]);
        }
        let _ = crc;
        start = block.end;
    }
    String::from_utf8(out).map_err(|e| e.to_string())
}

/// PNG-Vorschaubilder nach den Drucker-Metadaten einfuegen. None, wenn schon welche da sind.
pub fn with_thumbnails(data: &[u8], images: &[(u16, u16, Vec<u8>)]) -> Result<Option<Vec<u8>>, String> {
    let (crc, list) = blocks(data)?;
    if images.is_empty() || list.iter().any(|b| b.kind == THUMBNAIL) {
        return Ok(None);
    }
    let at = list.iter().find(|b| b.kind == PRINTER_METADATA).map(|b| b.end).ok_or("bgcode ohne Drucker-Metadaten")?;
    let mut inserted = Vec::new();
    for (width, height, png) in images {
        let mut block = Vec::with_capacity(png.len() + 20);
        block.extend_from_slice(&THUMBNAIL.to_le_bytes());
        block.extend_from_slice(&0u16.to_le_bytes()); // unkomprimiert
        block.extend_from_slice(&(png.len() as u32).to_le_bytes());
        block.extend_from_slice(&PNG.to_le_bytes());
        block.extend_from_slice(&width.to_le_bytes());
        block.extend_from_slice(&height.to_le_bytes());
        block.extend_from_slice(png);
        if crc {
            let sum = crc32fast::hash(&block);
            block.extend_from_slice(&sum.to_le_bytes());
        }
        inserted.extend_from_slice(&block);
    }
    let mut out = Vec::with_capacity(data.len() + inserted.len());
    out.extend_from_slice(&data[..at]);
    out.extend_from_slice(&inserted);
    out.extend_from_slice(&data[at..]);
    Ok(Some(out))
}

#[cfg(test)]
mod tests {
    use super::*;

    fn block(kind: u16, payload: &[u8], crc: bool) -> Vec<u8> {
        let mut b = Vec::new();
        b.extend_from_slice(&kind.to_le_bytes());
        b.extend_from_slice(&0u16.to_le_bytes());
        b.extend_from_slice(&(payload.len() as u32).to_le_bytes());
        b.extend_from_slice(&0u16.to_le_bytes()); // Kodierung
        b.extend_from_slice(payload);
        if crc {
            let sum = crc32fast::hash(&b);
            b.extend_from_slice(&sum.to_le_bytes());
        }
        b
    }

    fn file(crc: bool) -> Vec<u8> {
        let mut f = b"GCDE".to_vec();
        f.extend_from_slice(&1u32.to_le_bytes());
        f.extend_from_slice(&(crc as u16).to_le_bytes());
        for (kind, text) in [(0u16, "producer=x"), (3, "printer_model=MK3S"), (4, "time=1"), (2, "a=1"), (1, "G28")] {
            f.extend(block(kind, text.as_bytes(), crc));
        }
        f
    }

    #[test]
    fn thumbnails_follow_printer_metadata_with_valid_checksums() {
        for crc in [true, false] {
            let out = with_thumbnails(&file(crc), &[(64, 64, vec![137, 80, 78, 71]), (16, 16, vec![1])]).unwrap().unwrap();
            let (_, list) = blocks(&out).unwrap();
            assert_eq!(list.iter().map(|b| b.kind).collect::<Vec<_>>(), [0, 3, 5, 5, 4, 2, 1]);
            assert!(with_thumbnails(&out, &[(8, 8, vec![0])]).unwrap().is_none(), "nicht doppelt");
        }
    }

    #[test]
    fn text_from_the_engine_becomes_real_binary_gcode() {
        let nl = char::from(10).to_string();
        let text = ["; generated by PrusaSlicer 3.0.0-alpha14 on 2026", "; thumbnail begin 2x2 8", "; iVBORw0K", "; thumbnail end",
            "G28", "G1 X1 Y1 E0.5", "; filament used [mm] = 12.5", "; prusaslicer_config = begin", "; layer_height = 0.2",
            "; printer_model = MK3S", "; prusaslicer_config = end", ""].join(&nl);
        let out = from_ascii(&text);
        let (crc, list) = blocks(&out).unwrap();
        assert!(crc);
        assert_eq!(list.iter().map(|b| b.kind).collect::<Vec<_>>(), [0, 3, 5, 4, 2, 1]);
        let all = String::from_utf8_lossy(&out).into_owned();
        assert!(all.contains("printer_model=MK3S") && all.contains("layer_height=0.2") && all.contains("filament used [mm]=12.5"));
        assert!(all.contains("G1 X1 Y1 E0.5") && !all.contains("prusaslicer_config") && !all.contains("thumbnail begin"));
        // Grosse Dateien: mehrere G-Code-Bloecke, an Zeilenenden getrennt.
        let many = from_ascii(&format!("G1 X1 Y1{nl}").repeat(20000));
        assert!(blocks(&many).unwrap().1.iter().filter(|b| b.kind == 1).count() > 1);
    }

    #[test]
    fn broken_files_are_refused() {
        let mut f = file(true);
        let last = f.len() - 1;
        f[last] ^= 1;
        assert!(blocks(&f).is_err());
        assert!(blocks(b"; text gcode").is_err());
    }
}
