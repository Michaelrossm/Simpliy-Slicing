//! Vorschaubilder im G-Code (Kommentarbloecke fuer Drucker-Displays).
use super::*;

/// Vorschaubilder in den G-Code schreiben, im Format der Prusa-Engine (liest DWC, PrusaLink, OctoPrint).
/// Die Engine erzeugt sie beim Slicen ueber die Kommandozeile nicht.
#[derive(serde::Deserialize)]
pub struct Thumbnail { width: u32, height: u32, png: String }

#[tauri::command]
pub async fn add_thumbnails(path: String, images: Vec<Thumbnail>) -> Result<usize, String> {
    blocking(move || {
        let bytes = fs::read(&path).map_err(|e| e.to_string())?;
        let made = if bytes.starts_with(b"GCDE") {
            let pngs = images.iter().map(|i| Ok((i.width as u16, i.height as u16, STANDARD.decode(&i.png).map_err(|_| "Vorschaubild ungültig".to_string())?)))
                .collect::<Result<Vec<_>, String>>()?;
            bgcode::with_thumbnails(&bytes, &pngs)?
        } else {
            with_thumbnails(&String::from_utf8_lossy(&bytes), &images)?.map(String::into_bytes)
        };
        Ok(match made {
            Some(out) => {
                let temp = format!("{path}.thumb");
                fs::write(&temp, out).map_err(|e| e.to_string())?;
                fs::rename(&temp, &path).map_err(|e| e.to_string())?;
                images.len()
            }
            None => 0,
        })
    }).await
}

fn with_thumbnails(text: &str, images: &[Thumbnail]) -> Result<Option<String>, String> {
    if text.contains("; thumbnail begin") || images.is_empty() { return Ok(None); }
    let mut block = String::from(";
");
    for image in images {
        STANDARD.decode(&image.png).map_err(|_| "Vorschaubild ungültig".to_string())?;
        block += &format!("; thumbnail begin {}x{} {}
", image.width, image.height, image.png.len());
        for chunk in image.png.as_bytes().chunks(78) { block += &format!("; {}
", String::from_utf8_lossy(chunk)); }
        block += "; thumbnail end
;
";
    }
    // Nach den Kopfkommentaren der Engine, vor dem ersten Befehl.
    let at: usize = text.split_inclusive(char::from(10)).take_while(|l| l.starts_with(';') || l.trim().is_empty()).map(str::len).sum();
    Ok(Some(format!("{}{block}{}", &text[..at], &text[at..])))
}

#[cfg(test)]
mod thumbnail_tests {
    use super::*;
    #[test]
    fn block_goes_after_the_header_in_prusa_format() {
        let png = STANDARD.encode([137u8, 80, 78, 71]);
        let out = with_thumbnails("; generated by PrusaSlicer
;
G28
", &[Thumbnail { width: 64, height: 64, png: png.clone() }]).unwrap().unwrap();
        assert!(out.starts_with("; generated by PrusaSlicer
;
;
; thumbnail begin 64x64 8
"), "{out}");
        assert!(out.ends_with("; thumbnail end
;
G28
"));
        assert!(with_thumbnails(&out, &[Thumbnail { width: 1, height: 1, png }]).unwrap().is_none(), "nicht doppelt");
    }
}
